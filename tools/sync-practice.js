// Keep the bundled 3D practice app on the same data and engine as the main simulator.
// Run from any folder: node tools/sync-practice.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.resolve(__dirname, '..');
const practice = path.join(root, 'practice');
const vendor = path.join(practice, 'vendor', 'warlock-sim');
const manifest = JSON.parse(fs.readFileSync(path.join(vendor, 'manifest.json'), 'utf8'));
manifest.files.forEach(function (file) {
  fs.copyFileSync(path.join(root, file), path.join(vendor, file));
});
const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data', 'default-results.js'), 'utf8'), ctx);
const results = ctx.WL.DEFAULT_RESULTS, best = {};
results.results.forEach(function (result, i) {
  const key = results.keys[i];
  if (result.race === 'none') return;
  if (!best[key] || result.dps > best[key].dps) best[key] = { key: key, dps: result.dps, race: result.race };
});
const order = Object.values(best).sort(function (a, b) { return b.dps - a.dps; }).map(function (r) {
  return { key: r.key, dps: Math.round(r.dps * 10) / 10, race: r.race };
});
fs.writeFileSync(path.join(practice, 'data', 'build-order.js'),
  '// Generated by tools/sync-practice.js from the bundled simulator.\nwindow.FW_BUILD_ORDER = ' +
  JSON.stringify({ generated: results.generated, simCommit: manifest.commit, localChanges: true, order: order }, null, 2) + ';\n');
require(path.join(practice, 'tools', 'stamp.js'));
console.log('Synced ' + manifest.files.length + ' files and the build ranking into practice/.');
